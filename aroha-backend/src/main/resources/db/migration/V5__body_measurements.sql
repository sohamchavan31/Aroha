-- Tape measurements (cm), at most one row per user per day.
CREATE TABLE IF NOT EXISTS body_measurements (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL,
    log_date date NOT NULL,
    waist_cm double precision,
    neck_cm double precision,
    hip_cm double precision,
    chest_cm double precision,
    arm_cm double precision,
    shoulder_cm double precision,
    thigh_cm double precision
);
CREATE UNIQUE INDEX IF NOT EXISTS body_measurements_user_date_key ON body_measurements (user_id, log_date);
